#!/usr/bin/env python3
"""Measure one local run per gate arm; render/check the committed timing receipt."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import platform
import shlex
import signal
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "docs/_generated/gate-runtimes.json"
MD_PATH = JSON_PATH.with_suffix(".md")
ARMS = ("lint", "types", "test-fast", "test-full", "docs", "gnn", "package")


def render(data: dict) -> str:
    lines = [
        "# Local gate measurements", "",
        "<!-- Generated by scripts/measure_gates.py; do not hand-edit. -->", "",
        "One retained timing sample per arm/phase on this host; no statistical speedup claim.",
        "Setup/install time is excluded except for the package arm's clean install.",
        "The before fast selection applies the existing `not slow` marker directly;",
        "there was no default fast gate before this change. Full tests retain the",
        "95% branch-coverage requirement; fast tests are feedback, not release evidence.", "",
        "After selection also marks consumers of the real generated-bundle fixture",
        "as slow; full tests retain every consumer. Baseline source is an immutable",
        "archive of ad428a729b0b8fd94350e6f7a97a6cc1529e15f8.",
        "Caches were not normalized. Package baseline failed with an empty offline",
        "cache; subsequent runs use independently provisioned locked dependencies.", "",
        f"After working tree: `{data.get('contexts', {}).get('after', 'independent staging tree')}`.", "",
        "Offline setup probes and later verification are distinct from timed samples.",
        "Baseline supervisory source bindings changed and native Git index hashes",
        "differed; those failed observations are not source-current acceptance.",
        "Later intent probes disable optional Git index writes.", "",
        f"Host: `{data['host']}`; project Python `{data['python']}`.", "",
        "| Arm | Before (s) | After (s) | Before exit | After exit |",
        "| --- | ---: | ---: | ---: | ---: |",
    ]
    for arm in ARMS:
        cells = []
        for phase in ("before", "after"):
            row = data.get(phase, {}).get(arm)
            cells.append(f"{row['seconds']:.3f}" if row else "not measured")
        codes = [str(data.get(p, {}).get(arm, {}).get("exit", "--")) for p in ("before", "after")]
        lines.append(f"| `{arm}` | {' | '.join(cells + codes)} |")
    for phase in ("before", "after"):
        lines += ["", f"## {phase.title()} commands and outcomes", ""]
        for arm, row in data.get(phase, {}).items():
            lines += [f"### `{arm}`", "", "```text", row["command"], "```", ""]
            if row.get("summary"):
                lines += ["```text", row["summary"], "```", ""]
    if data.get("discarded_probes"):
        lines += ["## Superseded probes and failed attempts", "", "| Phase | Arm | Seconds | Reason |",
                  "| --- | --- | ---: | --- |"]
        for row in data["discarded_probes"]:
            lines.append(f"| {row['phase']} | {row['arm']} | {row['seconds']:.3f} | {row['reason']} |")
        lines += [""]
    if data.get("verification"):
        lines += ["## Subsequent verification", ""]
        for name, row in data["verification"].items():
            lines += [f"- `{name}`: exit {row['exit']}; {row['summary']}"]
        lines += [""]
    lines += [
        "## Refresh and check", "", "```sh",
        "./.venv/bin/python scripts/measure_gates.py --phase after --receipt tmp/estate/measurements.json",
        "./.venv/bin/python scripts/measure_gates.py --write --receipt tmp/estate/measurements.json",
        "./.venv/bin/python scripts/measure_gates.py --check", "```", "",
        "The JSON receipt preserves the command, exit status, elapsed wall time,",
        "output digest, and test/coverage summary. Check mode regenerates this page",
        "from that receipt without re-running tests or inventing new measurements.", "",
    ]
    return "\n".join(lines)


def save(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def baseline_commands(root: Path, arm: str) -> list[list[str]]:
    """Historical local/CI commands, kept separate from current gate definitions."""
    python = str(ROOT / ".venv/bin/python")
    paths = ["src", "scripts", "tests", "examples"]
    commands = {
        "lint": [[python, "-m", "compileall", "-q", *paths], [python, "-m", "ruff", "check", "--no-respect-gitignore", *paths]],
        "types": [[python, "-m", "mypy", *paths, "--ignore-missing-imports"]],
        "test-fast": [[python, "-m", "pytest", "tests/", "-m", "not slow", "-q"]],
        "test-full": [[python, "-m", "pytest", "tests/", "--cov=active_inference_power", "--cov-branch", "--cov-fail-under=95", "-q"]],
        "docs": [[python, "scripts/audit_documentation_links.py"]],
        "gnn": [[python, "scripts/validate_gnn_specs.py"], [python, "-m", "pytest", "tests/test_gnn_specs.py", "-q"]],
        "package": [[python, str(ROOT / "scripts/gate.py"), "package"]],
    }
    return commands[arm]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--phase", choices=("before", "after"))
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--receipt", type=Path, default=ROOT / "tmp/estate/measurements.json")
    parser.add_argument("--timeout", type=float, default=1500, help="Wall-time bound per arm (seconds).")
    parser.add_argument("--arms", nargs="+", choices=ARMS, default=list(ARMS))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if not math.isfinite(args.timeout) or args.timeout <= 0:
        parser.error("--timeout must be finite and positive")
    if args.check:
        data = json.loads(JSON_PATH.read_text(encoding="utf-8"))
        for phase in ("before", "after"):
            for row in data.get(phase, {}).values():
                if not math.isfinite(row["seconds"]) or row["seconds"] <= 0:
                    raise ValueError("invalid wall time")
        if MD_PATH.read_text(encoding="utf-8") != render(data):
            raise ValueError("generated measurements are stale; use --write with the receipt")
        print("Generated timing page matches its receipt")
        return 0
    data = json.loads(args.receipt.read_text()) if args.receipt.exists() else {
        "schema": "aip-gate-measurements/v1",
        "host": f"{platform.system()} {platform.release()} {platform.machine()}",
        "python": platform.python_version(),
    }
    failed = False
    if args.phase:
        root = args.root.resolve()
        data.setdefault("contexts", {})[args.phase] = str(root)
        for arm in args.arms:
            if arm in data.get(args.phase, {}):
                raise ValueError(f"{args.phase}/{arm} already measured; use a new receipt for a new run")
            commands = baseline_commands(root, arm) if args.phase == "before" else [[str(ROOT / "run.sh"), arm]]
            output = ""
            code = 0
            started = time.perf_counter()
            for command in commands:
                process = subprocess.Popen(
                    command, cwd=root, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                    stderr=subprocess.STDOUT, text=True, start_new_session=True,
                )
                remaining = max(0.01, args.timeout - (time.perf_counter() - started))
                try:
                    captured, _ = process.communicate(timeout=remaining)
                    code = process.wait()
                except subprocess.TimeoutExpired:
                    try:
                        os.killpg(process.pid, signal.SIGTERM)
                    except ProcessLookupError:
                        pass
                    try:
                        captured, _ = process.communicate(timeout=2)
                    except subprocess.TimeoutExpired:
                        try:
                            os.killpg(process.pid, signal.SIGKILL)
                        except ProcessLookupError:
                            pass
                        captured, _ = process.communicate()
                    code = 124
                    captured += f"\nArm timed out after {args.timeout:g}s; incomplete test evidence.\n"
                print(captured, end="", flush=True)
                output += captured
                failed = failed or code != 0
                if code:
                    break
            elapsed = time.perf_counter() - started
            summary = "\n".join(
                line for line in output.splitlines()
                if line.startswith(("====", "TOTAL", "Success:", "All checks passed", "gate:"))
                or any(s in line for s in ('"test_count"', '"branch_coverage_pct"', '"line_coverage_pct"'))
            )
            data.setdefault(args.phase, {})[arm] = {
                "seconds": elapsed, "exit": code,
                "command": " && ".join(shlex.join(c) for c in commands),
                "output_sha256": hashlib.sha256(output.encode()).hexdigest(),
                "summary": summary,
            }
            save(args.receipt, data)
            (args.receipt.parent / f"{args.phase}-{arm}.log").write_text(output, encoding="utf-8")
            print(f"MEASURE {args.phase}/{arm}: {elapsed:.3f}s exit={code}", flush=True)
    if args.write:
        save(JSON_PATH, data)
        MD_PATH.parent.mkdir(parents=True, exist_ok=True)
        MD_PATH.write_text(render(data), encoding="utf-8")
    return 1 if failed else 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError) as exc:
        print(str(exc), file=sys.stderr)
        raise SystemExit(1)
