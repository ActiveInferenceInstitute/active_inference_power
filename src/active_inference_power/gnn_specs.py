"""GNN specifications for the declared generative models.

The ``models/*.gnn.md`` files are the canonical structural description of the
agent-side generative models the suite evaluates (Generalized Notation
Notation, GNN v1.1). Numeric values stay generated by the runtime contracts —
``active_inference.build_generative_model`` and
``scenario.make_reference_action_scenario`` — and this module checks that the
declared state space, connections, ontology annotations, and any declared
``InitialParameterization`` agree with the runtime model.

``models/gnn-pin.json`` records the pinned Generalized_Notation_Notation
release the specifications are checked against. Nothing here imports upstream
GNN code: :data:`DIGEST_DRIVER_SOURCE` is a stdlib-only program the conformance
test runs with the pinned checkout's own interpreter, with the pinned commit's
``src/gnn`` extracted onto ``PYTHONPATH`` — so the bytes under test are the
pinned release's bytes, not the live working tree's.
"""

from __future__ import annotations

import ast
import datetime
import json
import os
import re
from collections import Counter
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

ArrayF = NDArray[np.float64]

#: Directory holding the shipped specifications and the custody pin.
SPEC_DIRNAME = "models"
#: Repository-relative path of the pinned upstream release identity.
PIN_RELATIVE_PATH = "models/gnn-pin.json"
#: Glob matching shipped specification files.
SPEC_GLOB = "*.gnn.md"
#: Conventional directory name of the sibling upstream checkout.
DEFAULT_UPSTREAM_DIRNAME = "Generalized_Notation_Notation"
#: Explicit checkout selection; when set it is final (empty values are refused).
ENV_UPSTREAM_ROOT = "ACTIVE_INFERENCE_POWER_GNN_ROOT"
#: Checkout-relative path of the upstream markdown parser module.
PARSER_RELATIVE_PATH = "src/gnn/parsers/markdown_parser.py"

_REQUIRED_SECTIONS = ("GNNSection", "GNNVersionAndFlags", "ModelName", "StateSpaceBlock", "Connections")
_SECTION_RE = re.compile(r"^##\s+(?P<name>.+?)\s*$")
_DECL_RE = re.compile(r"^(?P<name>[^\s\[]+)\[(?P<body>[^\]]*)\]\s*(?:#\s*(?P<comment>.*))?$")
_EDGE_RE = re.compile(r"^(?P<src>[^\s>\-]+)\s*(?P<op>[>\-])\s*(?P<dst>[^\s:>\-]+)(?::(?P<label>[\w]+))?$")
_PARAM_BLOCK_RE = re.compile(r"([^\s=]+)\s*=\s*\{")

_CORE_PIN_KEYS = ("repository", "commit", "version", "date_recorded")
_OPTIONAL_PIN_KEYS = ("tag", "parser_module", "parser_class")
_TAG_RE = re.compile(r"v\d+\.\d+\.\d+")
_VERSION_RE = re.compile(r"\d+\.\d+\.\d+")
_DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")
_COMMIT_RE = re.compile(r"[0-9a-f]{40}")
_MODULE_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)+")
_CLASS_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_DTYPE_ALIASES = {"integer": "int", "boolean": "bool", "string": "str"}


class GnnSpecError(ValueError):
    """Raised when a shipped GNN specification or custody pin is unusable."""


class UpstreamPinError(ValueError):
    """Raised when the pinned upstream release identity is malformed or unusable."""


@dataclass(frozen=True)
class GnnVariable:
    """One declared ``StateSpaceBlock`` variable."""

    name: str
    dims: tuple[int, ...]
    dtype: str
    value: ArrayF | None = None


@dataclass(frozen=True)
class GnnConnection:
    """One declared ``Connections`` edge."""

    source: str
    target: str
    directed: bool
    label: str | None = None


@dataclass(frozen=True)
class GnnSpec:
    """A parsed specification file (structure only; values stay runtime-owned)."""

    section: str
    version: str
    name: str
    variables: Mapping[str, GnnVariable] = field(default_factory=dict)
    connections: tuple[GnnConnection, ...] = ()
    ontology: Mapping[str, str] = field(default_factory=dict)
    model_parameters: Mapping[str, str] = field(default_factory=dict)
    time: str = ""


@dataclass(frozen=True)
class UpstreamPin:
    """The pinned upstream GNN release the specifications are checked against.

    ``repository``, ``commit``, ``version``, and ``date_recorded`` are the core
    identity every consumer declares. ``tag`` and the parser entry point are
    optional convenience fields validated when present, and any other key is
    carried in :attr:`extras` rather than refused, so a consumer can add digest
    maps or checkout hints without forking the schema.
    """

    repository: str
    commit: str
    version: str
    date_recorded: str
    tag: str | None = None
    parser_module: str | None = None
    parser_class: str | None = None
    extras: Mapping[str, object] = field(default_factory=dict)

    def parser_entry_point(self) -> tuple[str, str]:
        """Return the pinned parser module and class, or raise when undeclared."""
        if not self.parser_module or not self.parser_class:
            raise UpstreamPinError("upstream pin does not declare a parser entry point")
        return self.parser_module, self.parser_class


def load_upstream_pin(path: Path) -> UpstreamPin:
    """Read and validate the pinned upstream GNN release identity.

    Raises:
        UpstreamPinError: on an unreadable, ambiguous, or malformed pin.
    """

    def unique(pairs: list[tuple[str, object]]) -> dict[str, object]:
        result: dict[str, object] = {}
        for key, value in pairs:
            if key in result:
                raise UpstreamPinError(f"duplicate upstream pin field: {key}")
            result[key] = value
        return result

    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=unique)
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise UpstreamPinError(f"cannot read upstream pin {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise UpstreamPinError("upstream pin must be a JSON object")
    missing = [key for key in _CORE_PIN_KEYS if key not in data]
    if missing:
        raise UpstreamPinError(
            f"upstream pin must declare {list(_CORE_PIN_KEYS)}; missing {missing}"
        )
    declared = {key: data[key] for key in (*_CORE_PIN_KEYS, *_OPTIONAL_PIN_KEYS) if key in data}
    if not all(isinstance(value, str) for value in declared.values()):
        raise UpstreamPinError("upstream pin fields must be strings")
    if not str(data["repository"]).startswith("https://github.com/"):
        raise UpstreamPinError("upstream repository must be an HTTPS GitHub URL")
    if not _COMMIT_RE.fullmatch(str(data["commit"])):
        raise UpstreamPinError("upstream commit must be a complete Git object identity")
    if not _VERSION_RE.fullmatch(str(data["version"])):
        raise UpstreamPinError("upstream version must be a release version (major.minor.patch)")
    try:
        datetime.date.fromisoformat(str(data["date_recorded"]))
    except ValueError as exc:
        raise UpstreamPinError("upstream date_recorded must be an ISO date (YYYY-MM-DD)") from exc
    tag = data.get("tag")
    if tag is not None:
        if not _TAG_RE.fullmatch(str(tag)):
            raise UpstreamPinError("upstream tag must name a stable version (v<major>.<minor>.<patch>)")
        if str(tag).removeprefix("v") != str(data["version"]):
            raise UpstreamPinError("upstream tag and version must name the same release")
    parser_module = data.get("parser_module")
    if parser_module is not None and not _MODULE_RE.fullmatch(str(parser_module)):
        raise UpstreamPinError("upstream parser_module must be a dotted import path")
    parser_class = data.get("parser_class")
    if parser_class is not None and not _CLASS_RE.fullmatch(str(parser_class)):
        raise UpstreamPinError("upstream parser_class must be a Python identifier")
    extras = {key: value for key, value in data.items() if key not in declared}
    return UpstreamPin(
        repository=str(data["repository"]),
        commit=str(data["commit"]),
        version=str(data["version"]),
        date_recorded=str(data["date_recorded"]),
        tag=None if tag is None else str(tag),
        parser_module=None if parser_module is None else str(parser_module),
        parser_class=None if parser_class is None else str(parser_class),
        extras=extras,
    )


def default_gnn_root(project_root: Path) -> Path:
    """The conventional sibling checkout of the upstream GNN repository."""
    return (Path(project_root).parent / DEFAULT_UPSTREAM_DIRNAME).resolve()


def resolve_gnn_root(project_root: Path, env: Mapping[str, str] | None = None) -> Path:
    """Resolve the upstream checkout root.

    An explicit :data:`ENV_UPSTREAM_ROOT` selection is final, including refusal
    of an empty value; otherwise the conventional sibling checkout is used.

    Raises:
        UpstreamPinError: if the environment selection is set but empty.
    """
    environ = os.environ if env is None else env
    if ENV_UPSTREAM_ROOT in environ:
        raw = environ[ENV_UPSTREAM_ROOT].strip()
        if not raw:
            raise UpstreamPinError(f"{ENV_UPSTREAM_ROOT} must not be empty")
        return Path(raw).expanduser().resolve()
    return default_gnn_root(project_root)


def gnn_checkout_python(root: Path) -> Path:
    """The checkout-local interpreter used to execute the pinned parser."""
    return Path(root) / ".venv" / "bin" / "python"


def checkout_available(root: Path) -> bool:
    """Whether the checkout supplies both the upstream parser source and its interpreter."""
    return (Path(root) / PARSER_RELATIVE_PATH).is_file() and gnn_checkout_python(root).is_file()


def _split_sections(text: str) -> dict[str, str]:
    sections: dict[str, str] = {}
    current: str | None = None
    buffer: list[str] = []
    for line in text.splitlines():
        match = _SECTION_RE.match(line)
        if match:
            if current is not None:
                sections[current] = "\n".join(buffer).strip()
            current = match.group("name").strip()
            buffer = []
        elif current is not None:
            buffer.append(line)
    if current is not None:
        sections[current] = "\n".join(buffer).strip()
    return sections


def _parse_dims_and_dtype(source: str, name: str, body: str) -> tuple[tuple[int, ...], str]:
    dims: list[int] = []
    dtype: str | None = None
    for token in (part.strip() for part in body.split(",")):
        if not token:
            continue
        if "=" in token:
            key, _, value = token.partition("=")
            if key.strip() == "type":
                dtype = value.strip()
            continue
        if re.fullmatch(r"\d+", token):
            dims.append(int(token))
        else:
            raise GnnSpecError(f"{source}: variable {name!r}: unsupported dimension token {token!r}")
    if dtype is None:
        raise GnnSpecError(f"{source}: variable {name!r}: missing required 'type=' declaration")
    if not dims:
        raise GnnSpecError(f"{source}: variable {name!r}: no integer dimensions declared")
    return tuple(dims), dtype


def _parse_state_space(source: str, body: str) -> dict[str, tuple[tuple[int, ...], str]]:
    declarations: dict[str, tuple[tuple[int, ...], str]] = {}
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _DECL_RE.match(line)
        if not match:
            raise GnnSpecError(f"{source}: malformed StateSpaceBlock declaration: {line!r}")
        declarations[match.group("name")] = _parse_dims_and_dtype(source, match.group("name"), match.group("body"))
    return declarations


def _parse_connections(source: str, body: str) -> tuple[GnnConnection, ...]:
    edges: list[GnnConnection] = []
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = _EDGE_RE.match(line)
        if not match:
            raise GnnSpecError(f"{source}: malformed connection edge: {line!r}")
        edges.append(
            GnnConnection(
                source=match.group("src"),
                target=match.group("dst"),
                directed=match.group("op") == ">",
                label=match.group("label"),
            )
        )
    return tuple(edges)


def _parse_key_values(body: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in body.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if ":" in line:
            key, _, value = line.partition(":")
        elif "=" in line:
            key, _, value = line.partition("=")
        else:
            continue
        values[key.strip()] = value.strip()
    return values


def _parse_parameter_blocks(source: str, body: str) -> dict[str, ArrayF]:
    text = "\n".join(line for line in body.splitlines() if not line.strip().startswith("#"))
    values: dict[str, ArrayF] = {}
    index = 0
    while True:
        match = _PARAM_BLOCK_RE.search(text, index)
        if not match:
            break
        name = match.group(1)
        depth = 0
        end = match.end() - 1
        cursor = end
        while cursor < len(text):
            char = text[cursor]
            if char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    break
            cursor += 1
        if depth != 0:
            raise GnnSpecError(f"{source}: unbalanced braces in InitialParameterization for {name!r}")
        literal = text[end : cursor + 1].replace("{", "[").replace("}", "]").replace("(", "[").replace(")", "]")
        try:
            parsed = ast.literal_eval(literal)
        except (SyntaxError, ValueError) as exc:
            raise GnnSpecError(f"{source}: cannot read InitialParameterization for {name!r}: {exc}") from exc
        values[name] = np.asarray(parsed, dtype=np.float64)
        index = cursor + 1
    return values


def parse_spec(text: str, *, source: str = "<string>") -> GnnSpec:
    """Parse one GNN v1.1 specification into a structural :class:`GnnSpec`.

    Raises:
        GnnSpecError: on missing required sections or malformed declarations.
    """
    sections = _split_sections(text)
    for required in _REQUIRED_SECTIONS:
        if required not in sections:
            raise GnnSpecError(f"{source}: missing required section '## {required}'")
    declarations = _parse_state_space(source, sections["StateSpaceBlock"])
    parameter_values = _parse_parameter_blocks(source, sections.get("InitialParameterization", ""))
    variables: dict[str, GnnVariable] = {}
    for name, (dims, dtype) in declarations.items():
        value = parameter_values.get(name)
        variable = GnnVariable(name=name, dims=dims, dtype=dtype, value=value)
        if value is not None and value.size != variable_size(dims):
            raise GnnSpecError(f"{source}: variable {name!r} size mismatch between declaration and values")
        variables[name] = variable
    unknown_parameters = sorted(set(parameter_values) - set(declarations))
    if unknown_parameters:
        raise GnnSpecError(f"{source}: InitialParameterization names undeclared variables: {unknown_parameters}")
    # Canonical section spelling first; the spaced variant is the historical
    # alias the upstream parser normalizes (see models/AGENTS.md).
    ontology = _parse_key_values(sections.get("ActInfOntologyAnnotation", sections.get("ActInf Ontology Annotation", "")))
    return GnnSpec(
        section=sections["GNNSection"].strip(),
        version=sections["GNNVersionAndFlags"].strip(),
        name=sections["ModelName"].strip(),
        variables=variables,
        connections=_parse_connections(source, sections["Connections"]),
        ontology=ontology,
        model_parameters=_parse_key_values(sections.get("ModelParameters", "")),
        time=sections.get("Time", "").strip(),
    )


def variable_size(dims: tuple[int, ...]) -> int:
    """The element count implied by a declaration's dimensions."""
    size = 1
    for dim in dims:
        size *= dim
    return size


def spec_paths(project_root: Path) -> list[Path]:
    """The shipped specification files, sorted for deterministic reports."""
    return sorted((Path(project_root) / SPEC_DIRNAME).glob(SPEC_GLOB))


def _normalize_version(text: str) -> str:
    """Normalize ``GNN v1.1`` / ``1.1`` / ``v1.1`` to ``1.1``."""
    cleaned = str(text).strip()
    cleaned = re.sub(r"^GNN\s*", "", cleaned)
    return re.sub(r"^v", "", cleaned).strip()


def _normalize_time(text: str) -> str:
    """Classify a ``## Time`` section body the way upstream does.

    Upstream does not keep the section text: it scans the lines and records
    ``Static`` / ``Dynamic`` (later keyword wins, default ``Static``). The
    digest applies the same rule to the project-parsed body so the two sides
    are compared as classifications rather than raw text.
    """
    kind = "Static"
    for raw_line in str(text).splitlines():
        line = raw_line.strip().lower()
        if "dynamic" in line:
            kind = "Dynamic"
        elif "static" in line:
            kind = "Static"
    return kind


def _normalize_dtype(raw: object) -> str:
    """Normalize a declared dtype (``float`` / ``DataType.FLOAT`` / ``INTEGER``)."""
    text = str(raw).strip().lower()
    if "." in text:
        text = text.rsplit(".", 1)[-1]
    return _DTYPE_ALIASES.get(text, text)


def _normalized_param_text(value: object) -> str:
    """Text-normalize a ModelParameters value (sequences and comma lists included)."""
    if isinstance(value, (list, tuple)):
        return ",".join(_normalized_param_text(item) for item in value)
    text = str(value).strip()
    if "," in text:
        return ",".join(part.strip() for part in text.split(","))
    return text


def _normalize_direction(raw: object) -> str:
    """Normalize a connection direction token (``directed`` / ``ConnectionType.DIRECTED``)."""
    text = str(raw).strip()
    if "." in text:
        text = text.rsplit(".", 1)[-1]
    return text.lower()


def _normalized_edges(edges: Sequence[Sequence[object]]) -> Counter[tuple[str, str, str, str]]:
    """Connection edges as comparable 4-tuples, with the direction token normalized."""
    return Counter(
        (str(edge[0]), str(edge[1]), _normalize_direction(edge[2]), "" if edge[3] is None else str(edge[3]))
        for edge in edges
    )


def spec_digest(spec: GnnSpec) -> dict[str, object]:
    """Normalize a parsed specification into a conformance digest."""
    variables = {
        name: {"dims": [int(dim) for dim in variable.dims], "dtype": _normalize_dtype(variable.dtype)}
        for name, variable in spec.variables.items()
    }
    connections = sorted(
        [edge.source, edge.target, "directed" if edge.directed else "undirected", edge.label or ""]
        for edge in spec.connections
    )
    parameters = {
        name: np.asarray(variable.value, dtype=np.float64).tolist()
        for name, variable in spec.variables.items()
        if variable.value is not None
    }
    return {
        "model_name": spec.name.strip(),
        "version": _normalize_version(spec.version),
        "time": _normalize_time(spec.time),
        "variables": variables,
        "connections": connections,
        "ontology": dict(spec.ontology),
        "model_parameters": dict(spec.model_parameters),
        "parameters": parameters,
    }


def normalize_upstream_digest(payload: Mapping[str, object]) -> dict[str, object]:
    """Normalize the upstream driver's JSON digest into the project digest shape.

    Raises:
        UpstreamPinError: if the payload is missing required digest fields.
    """
    required = (
        "model_name",
        "version",
        "time",
        "variables",
        "connections",
        "ontology",
        "model_parameters",
        "parameters",
    )
    missing = [key for key in required if key not in payload]
    if missing:
        raise UpstreamPinError(f"upstream digest is missing fields: {missing}")

    raw_variables = payload["variables"]
    if not isinstance(raw_variables, Sequence):
        raise UpstreamPinError("upstream digest 'variables' must be a sequence")
    variables: dict[str, object] = {}
    for entry in raw_variables:
        if not isinstance(entry, Mapping):
            raise UpstreamPinError("upstream digest variable entries must be mappings")
        name = str(entry["name"])
        variables[name] = {"dims": [int(dim) for dim in entry["dims"]], "dtype": _normalize_dtype(entry["dtype"])}

    raw_connections = payload["connections"]
    if not isinstance(raw_connections, Sequence):
        raise UpstreamPinError("upstream digest 'connections' must be a sequence")
    connections = sorted(
        [str(edge[0]), str(edge[1]), _normalize_direction(edge[2]), "" if edge[3] is None else str(edge[3])]
        for edge in raw_connections
    )

    raw_ontology = payload["ontology"]
    if not isinstance(raw_ontology, Sequence):
        raise UpstreamPinError("upstream digest 'ontology' must be a sequence")
    ontology = {str(entry["variable"]): str(entry["term"]) for entry in raw_ontology}

    raw_parameters = payload["parameters"]
    raw_model_parameters = payload["model_parameters"]
    if not isinstance(raw_parameters, Mapping) or not isinstance(raw_model_parameters, Mapping):
        raise UpstreamPinError("upstream digest 'parameters' / 'model_parameters' must be mappings")

    return {
        "model_name": str(payload["model_name"]).strip(),
        "version": _normalize_version(str(payload["version"])),
        "time": _normalize_time(str(payload["time"])),
        "variables": variables,
        "connections": connections,
        "ontology": ontology,
        "model_parameters": {str(key): value for key, value in raw_model_parameters.items()},
        "parameters": {str(key): value for key, value in raw_parameters.items()},
    }


def _parameters_differ(project_value: object, upstream_value: object) -> bool:
    left = np.asarray(project_value, dtype=np.float64)
    right = np.asarray(upstream_value, dtype=np.float64)
    if left.shape != right.shape:
        return True
    return bool(np.abs(left - right).max() > 0.0) if left.size else False


def _mapping_field(digest: Mapping[str, object], key: str) -> dict[str, object]:
    """Read a digest field that must be a mapping.

    Raises:
        UpstreamPinError: if the field is absent-and-not-a-mapping or malformed.
    """
    value = digest.get(key, {})
    if not isinstance(value, Mapping):
        raise UpstreamPinError(f"digest field {key!r} must be a mapping, got {type(value).__name__}")
    return dict(value)


def digest_divergences(project: Mapping[str, object], upstream: Mapping[str, object]) -> list[str]:
    """Compare two conformance digests and describe every divergence.

    Returns an empty list when the two digests agree on model name, version,
    time, variables (dims + dtype), connections, ontology bindings,
    ``ModelParameters`` values, and parameterized values. Any non-empty list is
    a conformance failure.
    """
    issues: list[str] = []
    for field_name in ("model_name", "version", "time"):
        if project.get(field_name) != upstream.get(field_name):
            issues.append(f"{field_name}: project={project.get(field_name)!r} upstream={upstream.get(field_name)!r}")

    project_variables = _mapping_field(project, "variables")
    upstream_variables = _mapping_field(upstream, "variables")
    for name in sorted(set(project_variables) | set(upstream_variables)):
        if name not in project_variables:
            issues.append(f"variables: {name!r} declared upstream only")
        elif name not in upstream_variables:
            issues.append(f"variables: {name!r} declared in the project parser only")
        elif project_variables[name] != upstream_variables[name]:
            issues.append(f"variables[{name!r}]: project={project_variables[name]} upstream={upstream_variables[name]}")

    project_edges = _normalized_edges(project.get("connections", []))  # type: ignore[arg-type]
    upstream_edges = _normalized_edges(upstream.get("connections", []))  # type: ignore[arg-type]
    if project_edges != upstream_edges:
        issues.append(
            "connections differ: project-only "
            f"{sorted((project_edges - upstream_edges).elements())}, upstream-only "
            f"{sorted((upstream_edges - project_edges).elements())}"
        )

    if _mapping_field(project, "ontology") != _mapping_field(upstream, "ontology"):
        issues.append(f"ontology: project={project.get('ontology')!r} upstream={upstream.get('ontology')!r}")

    project_model_parameters = _mapping_field(project, "model_parameters")
    upstream_model_parameters = _mapping_field(upstream, "model_parameters")
    for key in sorted(set(project_model_parameters) | set(upstream_model_parameters)):
        if key not in project_model_parameters:
            issues.append(f"model_parameters: {key!r} present upstream only")
        elif key not in upstream_model_parameters:
            issues.append(f"model_parameters: {key!r} present in the project parser only")
        elif _normalized_param_text(project_model_parameters[key]) != _normalized_param_text(
            upstream_model_parameters[key]
        ):
            issues.append(
                f"model_parameters[{key!r}]: project={project_model_parameters[key]!r} "
                f"upstream={upstream_model_parameters[key]!r}"
            )

    project_parameters = _mapping_field(project, "parameters")
    upstream_parameters = _mapping_field(upstream, "parameters")
    for name in sorted(set(project_parameters) | set(upstream_parameters)):
        if name not in project_parameters:
            issues.append(f"parameters: {name!r} present upstream only")
        elif name not in upstream_parameters:
            issues.append(f"parameters: {name!r} present in the project parser only")
        elif _parameters_differ(project_parameters[name], upstream_parameters[name]):
            issues.append(
                f"parameters[{name!r}]: project={project_parameters[name]!r} upstream={upstream_parameters[name]!r}"
            )
    return issues


def runtime_matrices(spec_name: str) -> dict[str, ArrayF]:
    """Runtime matrices for a declared model, keyed by GNN variable name.

    The values are produced by the real runtime contracts, never by this
    module: the sequential evidence agent comes from
    :func:`active_inference_power.active_inference.build_generative_model` at
    its default configuration, and the reference action loop from
    :func:`active_inference_power.scenario.make_reference_action_scenario`.

    Raises:
        GnnSpecError: if no runtime model is registered for ``spec_name``.
    """
    if spec_name == "sequential_evidence_agent":
        from .active_inference import AITestConfig, build_generative_model

        likelihood, transition, preferences, prior = build_generative_model(AITestConfig())
        return {
            "A": np.asarray(likelihood[0], dtype=float),
            "B": np.asarray(transition[0], dtype=float),
            "C": np.asarray(preferences[0], dtype=float),
            "D": np.asarray(prior[0], dtype=float),
        }
    if spec_name == "reference_action_loop":
        from .scenario import make_reference_action_scenario

        scenario = make_reference_action_scenario()
        return {
            "A": np.asarray(scenario.model.likelihood, dtype=float),
            "B": np.asarray(scenario.model.transition, dtype=float),
            "C": np.asarray(scenario.model.preferences, dtype=float),
            "D": np.asarray(scenario.model.prior, dtype=float),
        }
    raise GnnSpecError(f"no runtime model is registered for specification {spec_name!r}")


def binding_issues(spec: GnnSpec, runtime: Mapping[str, ArrayF]) -> list[str]:
    """Report declarations that disagree with the runtime model arrays.

    Every runtime matrix must be declared with exactly its runtime shape. A
    declaration that also carries ``InitialParameterization`` values must
    reproduce the runtime values: the declared block is reshaped to the runtime
    shape (GNN writes vectors as ``{(a, b)}``, which parses as a 1 x n row) and
    compared with an absolute tolerance of ``1e-12`` that only absorbs decimal
    literals rounded through binary floats (``1.0 - 0.8`` vs ``0.2``).
    Conceptual variables without a runtime counterpart (state, observation,
    action, posterior) are not constrained here.
    """
    issues: list[str] = []
    for name, matrix in sorted(runtime.items()):
        declared = spec.variables.get(name)
        if declared is None:
            issues.append(f"{name}: runtime matrix with shape {tuple(matrix.shape)} is not declared")
            continue
        if tuple(declared.dims) != tuple(matrix.shape):
            issues.append(f"{name}: declared dims {tuple(declared.dims)} != runtime shape {tuple(matrix.shape)}")
            continue
        if declared.value is None:
            continue
        values = np.asarray(declared.value, dtype=float)
        if values.size != matrix.size:
            issues.append(f"{name}: declared {values.size} values != runtime matrix size {matrix.size}")
        elif not np.allclose(values.reshape(matrix.shape), matrix, rtol=0.0, atol=1e-12):
            issues.append(f"{name}: declared values differ from the runtime model")
    return issues


def check_specs(project_root: Path) -> dict[str, object]:
    """Validate every shipped specification against its runtime model and the pin.

    Returns a deterministic report; ``passed`` is true only when the pin parses
    and every specification binds to its registered runtime model.
    """
    root = Path(project_root)
    pin = load_upstream_pin(root / PIN_RELATIVE_PATH)
    rows: list[dict[str, object]] = []
    for path in spec_paths(root):
        spec = parse_spec(path.read_text(encoding="utf-8"), source=str(path))
        runtime_name = path.name.removesuffix(".gnn.md")
        issues = binding_issues(spec, runtime_matrices(runtime_name))
        rows.append(
            {
                "spec": path.relative_to(root).as_posix(),
                "model_name": spec.name,
                "runtime_model": runtime_name,
                "variable_count": len(spec.variables),
                "connection_count": len(spec.connections),
                "ontology_terms": len(spec.ontology),
                "binding_issues": issues,
                "passed": not issues,
            }
        )
    return {
        "schema_version": "1.0",
        "pin": {
            "repository": pin.repository,
            "commit": pin.commit,
            "version": pin.version,
            "date_recorded": pin.date_recorded,
        },
        "specs": rows,
        "passed": bool(rows) and all(row["passed"] for row in rows),
    }


